"use client";

import { APP_NAME } from "@kedge/config";
import {
  Alert,
  Badge,
  Button,
  Card,
  CardContent,
  CardDescription,
  CardFooter,
  CardHeader,
  CardTitle,
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogTitle,
  Field,
  Input,
} from "@kedge/ui";
import { ShieldCheck } from "lucide-react";
import { useRouter } from "next/navigation";
import { useState, type FormEvent } from "react";
import { api } from "@/lib/api";
import { supabaseBrowser } from "@/lib/supabase/browser";

interface Enrolment {
  factorId: string;
  qrCode: string;
  secret: string;
}

/** TOTP two-step verification (AC-0.1): enrol, verify and remove. */
export function MfaSection({ enabled }: { enabled: boolean }) {
  const router = useRouter();
  const [enrolment, setEnrolment] = useState<Enrolment | null>(null);
  const [confirmRemove, setConfirmRemove] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [pending, setPending] = useState(false);

  async function start() {
    setPending(true);
    setError(null);
    const supabase = supabaseBrowser();
    // Clear any half-finished enrolment from an earlier attempt.
    const { data: existing } = await supabase.auth.mfa.listFactors();
    for (const f of existing?.all ?? []) {
      if (f.status === "unverified") await supabase.auth.mfa.unenroll({ factorId: f.id });
    }
    const { data, error: enrolError } = await supabase.auth.mfa.enroll({ factorType: "totp", friendlyName: `${APP_NAME} authenticator` });
    setPending(false);
    if (enrolError || !data) {
      setError("We couldn't start set-up. Please try again.");
      return;
    }
    setEnrolment({ factorId: data.id, qrCode: data.totp.qr_code, secret: data.totp.secret });
  }

  async function verify(e: FormEvent<HTMLFormElement>) {
    e.preventDefault();
    if (!enrolment) return;
    const code = String(new FormData(e.currentTarget).get("code") ?? "").replace(/\s/g, "");
    setPending(true);
    setError(null);
    const { error: verifyError } = await supabaseBrowser().auth.mfa.challengeAndVerify({ factorId: enrolment.factorId, code });
    if (verifyError) {
      setPending(false);
      setError("That code didn't work. Check the time on your phone and try the current code.");
      return;
    }
    await api.syncMfa();
    setPending(false);
    setEnrolment(null);
    router.refresh();
  }

  async function remove() {
    setPending(true);
    setError(null);
    const supabase = supabaseBrowser();
    const { data } = await supabase.auth.mfa.listFactors();
    for (const f of data?.totp ?? []) {
      const { error: unenrolError } = await supabase.auth.mfa.unenroll({ factorId: f.id });
      if (unenrolError) {
        setPending(false);
        setConfirmRemove(false);
        setError("We couldn't turn off two-step verification. Log in again and retry.");
        return;
      }
    }
    await supabase.auth.refreshSession();
    await api.syncMfa();
    setPending(false);
    setConfirmRemove(false);
    router.refresh();
  }

  return (
    <Card>
      <CardHeader>
        <div className="flex items-center gap-2">
          <CardTitle>Two-step verification</CardTitle>
          {enabled ? <Badge tone="success">On</Badge> : <Badge>Off</Badge>}
        </div>
        <CardDescription>Ask for a code from an authenticator app (such as Google Authenticator or 1Password) every time you log in.</CardDescription>
      </CardHeader>
      <CardContent className="grid gap-4">
        {error ? <Alert tone="danger" title={error} /> : null}
        {enrolment ? (
          <form onSubmit={verify} className="grid gap-4 sm:grid-cols-[auto_1fr] sm:items-start">
            {/* QR code is an SVG data URI generated by the auth provider. */}
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img src={enrolment.qrCode} alt="QR code to scan with your authenticator app" className="size-44 rounded-lg border border-border bg-white p-2" />
            <div className="grid gap-3">
              <p className="text-sm">Scan the code with your authenticator app, then enter the 6-digit code it shows.</p>
              <p className="text-xs text-muted">
                Can&apos;t scan? Enter this key instead: <code className="font-mono break-all text-foreground">{enrolment.secret}</code>
              </p>
              <Field id="totp-code" label="Code from the app">
                <Input id="totp-code" name="code" inputMode="numeric" autoComplete="one-time-code" maxLength={7} className="tabular max-w-40 tracking-widest" autoFocus />
              </Field>
              <div className="flex gap-2">
                <Button type="submit" disabled={pending}>
                  {pending ? "Checking…" : "Turn on"}
                </Button>
                <Button variant="ghost" onClick={() => setEnrolment(null)}>
                  Cancel
                </Button>
              </div>
            </div>
          </form>
        ) : null}
      </CardContent>
      {enrolment ? null : (
        <CardFooter>
          {enabled ? (
            <Button variant="secondary" onClick={() => setConfirmRemove(true)}>
              Turn off
            </Button>
          ) : (
            <Button onClick={start} disabled={pending}>
              <ShieldCheck aria-hidden />
              Set up two-step verification
            </Button>
          )}
        </CardFooter>
      )}

      <Dialog open={confirmRemove} onOpenChange={setConfirmRemove}>
        <DialogContent>
          <DialogTitle>Turn off two-step verification?</DialogTitle>
          <DialogDescription>Your authenticator app will be removed from this account. From your next login, only your password will be needed.</DialogDescription>
          <DialogFooter>
            <Button variant="secondary" onClick={() => setConfirmRemove(false)}>
              Keep it on
            </Button>
            <Button variant="danger" onClick={remove} disabled={pending}>
              {pending ? "Turning off…" : "Turn off"}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </Card>
  );
}
