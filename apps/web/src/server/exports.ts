import type { ReportResponse } from "@kedge/api";
import { APP_NAME } from "@kedge/config";
import { formatMoney } from "@kedge/core";
import ExcelJS from "exceljs";

/** Plain decimal naira for files ("1234.56"), exact from minor units. */
const plain = (minor: string) => formatMoney(BigInt(minor), "NGN", { symbol: false }).replace(/,/g, "").replace(/^\((.*)\)$/, "-$1");
/**
 * Spreadsheet cells hold numbers. The value is built from the exact decimal
 * string, so the only approximation is Excel's own double representation at
 * the export edge; displayed figures (2 d.p.) are exact.
 */
const num = (minor: string) => Number(plain(minor));

const csvCell = (v: string) => (/[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);

export const REPORT_TITLES: Record<ReportResponse["report"], string> = {
  "trial-balance": "Trial balance",
  "general-ledger": "General ledger",
  "income-statement": "Income statement",
  "balance-sheet": "Balance sheet",
  journal: "Journal report",
  "expense-by-category": "Expenses by category",
  "income-by-source": "Income by source",
};

type Statement = Extract<ReportResponse, { report: "income-statement" | "balance-sheet" }>;
type Section = Extract<ReportResponse, { report: "income-statement" }>["revenue"];

function statementPlan(r: Statement): { blocks: ({ kind: "section"; label: string; section: Section } | { kind: "total"; label: string; refs: [string, "+" | "-"][]; figure: { amount: string; comparative: string | null }; name: string })[] } {
  if (r.report === "income-statement") {
    return {
      blocks: [
        { kind: "section", label: "Revenue", section: r.revenue },
        { kind: "section", label: "Cost of sales", section: r.costOfSales },
        { kind: "total", name: "gross", label: "Gross profit", refs: [["revenue", "+"], ["cost_of_sales", "-"]], figure: r.grossProfit },
        { kind: "section", label: "Operating expenses", section: r.operatingExpenses },
        { kind: "total", name: "operating", label: "Operating profit", refs: [["gross", "+"], ["operating_expenses", "-"]], figure: r.operatingProfit },
        { kind: "section", label: "Other income", section: r.otherIncome },
        { kind: "section", label: "Finance costs", section: r.financeCosts },
        { kind: "total", name: "pbt", label: "Profit before tax", refs: [["operating", "+"], ["other_income", "+"], ["finance_costs", "-"]], figure: r.profitBeforeTax },
        { kind: "section", label: "Income tax", section: r.incomeTax },
        { kind: "total", name: "profit", label: "Profit for the period", refs: [["pbt", "+"], ["income_tax", "-"]], figure: r.profitForPeriod },
      ],
    };
  }
  return {
    blocks: [
      { kind: "section", label: "Non-current assets", section: r.nonCurrentAssets },
      { kind: "section", label: "Current assets", section: r.currentAssets },
      { kind: "total", name: "assets", label: "Total assets", refs: [["non_current_assets", "+"], ["current_assets", "+"]], figure: r.totalAssets },
      { kind: "section", label: "Equity", section: r.equity },
      { kind: "total", name: "prior", label: "Retained profit from earlier years", refs: [], figure: r.priorYearsEarnings },
      { kind: "total", name: "cye", label: "Current year earnings", refs: [], figure: r.currentYearEarnings },
      { kind: "total", name: "equity_total", label: "Total equity", refs: [["equity", "+"], ["prior", "+"], ["cye", "+"]], figure: r.totalEquity },
      { kind: "section", label: "Non-current liabilities", section: r.nonCurrentLiabilities },
      { kind: "section", label: "Current liabilities", section: r.currentLiabilities },
      { kind: "total", name: "liabilities", label: "Total liabilities", refs: [["non_current_liabilities", "+"], ["current_liabilities", "+"]], figure: r.totalLiabilities },
      { kind: "total", name: "le", label: "Total equity and liabilities", refs: [["equity_total", "+"], ["liabilities", "+"]], figure: { amount: (BigInt(r.totalEquity.amount) + BigInt(r.totalLiabilities.amount)).toString(), comparative: r.totalEquity.comparative === null || r.totalLiabilities.comparative === null ? null : (BigInt(r.totalEquity.comparative) + BigInt(r.totalLiabilities.comparative)).toString() } },
    ],
  };
}

export function reportToCsv(r: ReportResponse, entityName: string): string {
  const rows: string[][] = [[`${entityName} — ${REPORT_TITLES[r.report]}`], [`Generated by ${APP_NAME}. Accrual basis. Amounts in NGN.`], []];
  switch (r.report) {
    case "trial-balance":
      rows.push(["Code", "Account", "Debit", "Credit"], ...r.rows.map((x) => [x.account.code, x.account.name, plain(x.debit), plain(x.credit)]), ["", "Total", plain(r.totalDebit), plain(r.totalCredit)]);
      break;
    case "general-ledger":
      rows.push(["Account", "Date", "Entry", "Description", "Debit", "Credit", "Balance"]);
      for (const a of r.accounts) {
        rows.push([`${a.account.code} ${a.account.name}`, "", "", "Opening balance", "", "", plain(a.opening)]);
        for (const x of a.rows) rows.push(["", x.date, x.entryNumber, x.description ?? x.memo, plain(x.debit), plain(x.credit), plain(x.balance)]);
        rows.push(["", "", "", "Closing balance", plain(a.totalDebit), plain(a.totalCredit), plain(a.closing)]);
      }
      break;
    case "income-statement":
    case "balance-sheet": {
      const cmp = r.report === "income-statement" ? r.comparativeFrom !== null : r.comparativeAsOf !== null;
      rows.push(["Line", "Amount", ...(cmp ? ["Comparative"] : [])]);
      for (const b of statementPlan(r).blocks) {
        if (b.kind === "section") {
          rows.push([b.label]);
          for (const x of b.section.rows) rows.push([`  ${x.account.code} ${x.account.name}`, plain(x.amount), ...(cmp ? [plain(x.comparative ?? "0")] : [])]);
          rows.push([`Total ${b.label.toLowerCase()}`, plain(b.section.total), ...(cmp ? [plain(b.section.comparativeTotal ?? "0")] : [])]);
        } else {
          rows.push([b.label, plain(b.figure.amount), ...(cmp ? [plain(b.figure.comparative ?? "0")] : [])]);
        }
      }
      break;
    }
    case "journal":
      rows.push(["Number", "Date", "Memo", "Account", "Debit", "Credit"]);
      for (const e of r.entries) for (const l of e.lines) rows.push([e.number, e.date, e.memo, `${l.account.code} ${l.account.name}`, plain(l.debit), plain(l.credit)]);
      break;
    case "expense-by-category":
    case "income-by-source":
      rows.push(["Category", "Amount", "Share %"], ...r.rows.map((x) => [x.account.name, plain(x.amount), (x.shareBps / 100).toString()]), ["Total", plain(r.total), "100"]);
      break;
  }
  return `${rows.map((r2) => r2.map(csvCell).join(",")).join("\n")}\n`;
}

/** XLSX with live formulas for every subtotal and total (AC-1.11). */
export async function reportToXlsx(r: ReportResponse, entityName: string): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = APP_NAME;
  const ws = wb.addWorksheet(REPORT_TITLES[r.report].slice(0, 31));
  ws.addRow([`${entityName} — ${REPORT_TITLES[r.report]}`]).font = { bold: true, size: 13 };
  ws.addRow([`Generated by ${APP_NAME} on ${new Date().toISOString().slice(0, 10)}. Accrual basis. Amounts in NGN.`]).font = { italic: true, color: { argb: "FF666666" } };
  ws.addRow([]);
  const money = "#,##0.00;(#,##0.00);-";
  const header = (cells: string[]) => {
    const row = ws.addRow(cells);
    row.font = { bold: true };
    row.border = { bottom: { style: "thin" } };
  };

  if (r.report === "trial-balance") {
    header(["Code", "Account", "Debit", "Credit"]);
    const first = ws.rowCount + 1;
    for (const x of r.rows) ws.addRow([x.account.code, x.account.name, num(x.debit), num(x.credit)]);
    const last = ws.rowCount;
    const total = ws.addRow(["", "Total", { formula: `SUM(C${first}:C${last})`, result: num(r.totalDebit) }, { formula: `SUM(D${first}:D${last})`, result: num(r.totalCredit) }]);
    total.font = { bold: true };
    ws.getColumn(3).numFmt = money;
    ws.getColumn(4).numFmt = money;
  } else if (r.report === "income-statement" || r.report === "balance-sheet") {
    const cmp = r.report === "income-statement" ? r.comparativeFrom !== null : r.comparativeAsOf !== null;
    header(["", "Amount", ...(cmp ? ["Comparative"] : [])]);
    const refs: Record<string, number> = {};
    for (const b of statementPlan(r).blocks) {
      if (b.kind === "section") {
        ws.addRow([b.label]).font = { bold: true };
        const first = ws.rowCount + 1;
        for (const x of b.section.rows) ws.addRow([`   ${x.account.name}`, num(x.amount), ...(cmp ? [num(x.comparative ?? "0")] : [])]);
        const last = ws.rowCount;
        const sum = (col: string) => (last >= first ? `SUM(${col}${first}:${col}${last})` : "0");
        const row = ws.addRow([
          `Total ${b.label.toLowerCase()}`,
          { formula: sum("B"), result: num(b.section.total) },
          ...(cmp ? [{ formula: sum("C"), result: num(b.section.comparativeTotal ?? "0") }] : []),
        ]);
        row.font = { bold: true };
        refs[b.section.key] = row.number;
      } else {
        const expr = (col: string) => b.refs.map(([k, sign], i) => `${i === 0 && sign === "+" ? "" : sign}${col}${refs[k]}`).join("");
        const row = ws.addRow([
          b.label,
          b.refs.length > 0 ? { formula: expr("B"), result: num(b.figure.amount) } : num(b.figure.amount),
          ...(cmp ? [b.refs.length > 0 ? { formula: expr("C"), result: num(b.figure.comparative ?? "0") } : num(b.figure.comparative ?? "0")] : []),
        ]);
        row.font = { bold: true };
        row.border = { top: { style: "thin" } };
        refs[b.name] = row.number;
      }
    }
    ws.getColumn(2).numFmt = money;
    ws.getColumn(3).numFmt = money;
  } else {
    // Tabular reports: reuse the CSV layout, with numeric cells.
    const csv = reportToCsv(r, entityName).trim().split("\n").slice(3);
    csv.forEach((line, i) => {
      const cells = line.split(",").map((c) => (/^-?\d+(\.\d+)?$/.test(c) ? Number(c) : c.replace(/^"|"$/g, "")));
      const row = ws.addRow(cells);
      if (i === 0) row.font = { bold: true };
    });
    ws.columns.forEach((c) => {
      c.numFmt = money;
    });
  }
  ws.getColumn(1).width = r.report === "trial-balance" ? 10 : 44;
  ws.getColumn(2).width = r.report === "trial-balance" ? 40 : 18;
  ws.getColumn(3).width = 18;
  ws.getColumn(4).width = 18;
  return Buffer.from(await wb.xlsx.writeBuffer());
}
